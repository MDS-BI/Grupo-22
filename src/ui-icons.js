export const iconNames = Object.freeze(Object.keys(iconPaths));

function escapeAttribute(value) {
  return String(value).replace(/[&<>"']/g, character => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  })[character]);
}

export function icon(name, options = {}) {
  const path = iconPaths[name];
  if (!path) return '';
  const className = options.className ? ` class="${escapeAttribute(options.className)}"` : '';
  const label = options.label
    ? ` role="img" aria-label="${escapeAttribute(options.label)}"`
    : ' aria-hidden="true"';
  return `<svg${className} width="1em" height="1em" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" focusable="false"${label}>${path}</svg>`;
}

export function hydrateIcons(root = document) {
  for (const host of root.querySelectorAll('[data-icon]')) {
    const markup = icon(host.dataset.icon, { className: 'ui-icon' });
    if (!markup) continue;
    host.innerHTML = markup;
    host.setAttribute('aria-hidden', 'true');
  }
}
